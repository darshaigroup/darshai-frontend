// Helper lookup by slug or alias
export function getCentreBySlug(slug) {
    if (!slug)
        return undefined;
    const normalized = slug.toLowerCase().trim();
    // Direct key lookup
    if (CENTRES_DATA[normalized]) {
        return CENTRES_DATA[normalized];
    }
    // Common spelling normalizations
    if (normalized.includes("chitrakoota") || normalized.includes("chithrakoota")) {
        return CENTRES_DATA.chitrakoota;
    }
    if (normalized.includes("shathayu")) {
        return CENTRES_DATA.shathayu;
    }
    if (normalized.includes("kanasu")) {
        return CENTRES_DATA.kanasu;
    }
    // Alias search
    return Object.values(CENTRES_DATA).find((centre) => centre.slug === normalized ||
        centre.aliases.some((a) => a.toLowerCase() === normalized || a.toLowerCase().replace(/-/g, "") === normalized.replace(/-/g, "")));
}
